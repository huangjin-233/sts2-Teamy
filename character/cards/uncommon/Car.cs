using Teamy.character.power;

namespace Teamy.character.cards.common;

 [RegisterCard(typeof(TeamyCardPool))]
    public class Car : ModCardTemplate
    {
        public override bool GainsBlock => true;
        // 基础耗能
        private const int energyCost = 1;
        // 卡牌类型
        private const CardType type = CardType.Skill;
        // 卡牌稀有度
        private const CardRarity rarity = CardRarity.Uncommon;
        // 目标类型（AnyEnemy表示任意敌人）
        private const TargetType targetType = TargetType.Self;
        // 是否在卡牌图鉴中显示
        private const bool shouldShowInCardLibrary = true;
        public override IEnumerable<CardKeyword> CanonicalKeywords => [TeamyKeyword.Gou,TeamyKeyword.Xty];
        // 卡图资源
        public override CardAssetProfile AssetProfile => new(
            PortraitPath: $"res://images/cards/skill/{GetType().Name}.png"
        );
        protected override List<DynamicVar> CanonicalVars => [
            new HpLossVar(15)
        ];
        // 卡牌基础数值

        public Car () : base(energyCost, type, rarity, targetType, shouldShowInCardLibrary)
        {
        }

        // 打出时的效果逻辑
        protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
        {
            await CreatureCmd.Damage(choiceContext, base.Owner.Creature, base.DynamicVars.HpLoss.BaseValue, ValueProp.Unblockable | ValueProp.Unpowered | ValueProp.Move, this); 
            await PowerCmd.Apply<BufferPower>(choiceContext,Owner.Creature, 1, Owner.Creature, null);
        }

        // 升级后的效果逻辑
        protected override void OnUpgrade()
        {
           DynamicVars.HpLoss.UpgradeValueBy(-5);
        }
        protected override IEnumerable<IHoverTip> AdditionalHoverTips => [
        ];
    }